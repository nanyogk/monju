def get_i18n(locale: str = "ja", overrides: dict[str, Any] | None = None) -> dict[str, str]:
    """Return merged UI string dictionary for the given locale."""
    base = dict(LOCALES.get(locale, LOCALES["ja"]))
    if overrides:
        for k, v in overrides.items():
            if isinstance(v, str):
                base[k] = v
    return base
